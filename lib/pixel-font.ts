const parseGlyph = (source: string): PixelGlyph => {
  const sourceRows = source.split('/');
  const width = Math.max(...sourceRows.map((row) => row.length));
  return {
    rows: sourceRows.map((row) => parseInt(row.padEnd(width, '0'), 2)),
    width,
  };
};

const glyphs = new Map(Object.entries(glyphSource).map(([character, source]) => [character, parseGlyph(source)]));

export const getPixelGlyph = (character: string) => glyphs.get(character) ?? glyphs.get('?') as PixelGlyph;

