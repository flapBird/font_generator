test('homepage keeps all 59 styles, filters and search while revealing results incrementally', async ({ page, request }) => {
  await page.goto('/');
  await expect(page.locator('#generator-input')).toHaveValue('Free Font Generator');
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href', 'https://font-generators.org/');
  await expect(page.locator('#generator-input')).toHaveAttribute('maxlength', '240');
  await expect(page.locator('#generated-results article')).toHaveCount(8);
  while (await page.getByRole('button', { name: /^Show more styles/ }).count()) await page.getByRole('button', { name: /^Show more styles/ }).click();
  await expect(page.locator('#generated-results article')).toHaveCount(59);
  await expect(page.getByRole('button', { name: 'Copy Bold Sans Font result', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Classic', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Classic', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('#generated-results article')).toHaveCount(8);
  await page.getByRole('button', { name: 'All styles', exact: true }).click();
  await page.getByRole('button', { name: 'Find a style', exact: true }).click();
  const search = page.getByRole('searchbox', { name: 'Search styles', exact: true });
  await expect(search).toBeFocused();
  await search.fill('cursive');
  await expect(page.getByRole('button', { name: 'Copy Elegant Script Font result', exact: true })).toBeVisible();
  await search.fill('style-does-not-exist');
  await expect(page.getByRole('heading', { name: 'No styles found.' })).toBeVisible();
  await page.getByRole('button', { name: 'Show all styles', exact: true }).click();
  await expect(search).toHaveValue('');
  await expect(page.locator('#generated-results article')).toHaveCount(8);
  const html = await (await request.get('/')).text();
  for (const text of ['Create Fancy Text in Three Steps', 'Font Generator Questions, Answered', 'What This Font Generator Changes']) expect(html).toContain(text);
  const llms = await (await request.get('/llms.txt')).text();
  expect(llms).toContain('Results initially show eight styles');
  expect(llms).toContain('expandable with Generators on phones');
});

test('homepage copies Unicode, preserves text through previews and recovers from a blocked clipboard', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.goto('/');
  await page.locator('#generator-input').fill('Ab 12 👋');
  const copy = page.getByRole('button', { name: 'Copy Bold Serif Font result', exact: true });
  await copy.focus(); await page.keyboard.press('Enter');
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe('𝐀𝐛 𝟏𝟐 👋');
  const trigger = page.getByRole('button', { name: 'Preview Italic Serif Font', exact: true });
  await trigger.click();
  const preview = page.getByRole('region', { name: 'Selected font preview', exact: true });
  await expect(preview).toContainText('𝐴𝑏 12 👋');
  await expect(preview.getByRole('heading')).toBeFocused();
  await page.getByLabel('Size', { exact: true }).focus();
  await page.keyboard.press('End');
  await expect(preview.locator('p')).toHaveCSS('font-size', '64px');
  await expect(page.locator('#generator-input')).toHaveValue('Ab 12 👋');
  await page.keyboard.press('Escape');
  await expect(preview).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await page.evaluate(() => { Object.defineProperty(navigator.clipboard, 'writeText', { value: () => Promise.reject(new Error('denied')) }); });
  await copy.click();
  const manual = page.getByLabel('Copy this text manually', { exact: true });
  await expect(manual).toHaveValue('𝐀𝐛 𝟏𝟐 👋');
  await expect(manual).toBeFocused();
  await expect(page.getByRole('status').filter({ hasText: 'blocked' })).toBeVisible();
  await expect(page.getByText('Copied', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Clear input', exact: true }).click();
  await expect(page.locator('#generator-input')).toHaveValue('');
  await expect(page.getByRole('heading', { name: 'Start with a few words.' })).toBeVisible();
  await page.getByRole('button', { name: 'Use sample text', exact: true }).click();
  await expect(page.locator('#generator-input')).toHaveValue('Free Font Generator');
  await expect(page.locator('#generated-results article')).toHaveCount(8);
});

test('homepage responsive directory, previews and artwork retain routes without loading the matcher', async ({ page }) => {
  const requests: string[] = [], errors: string[] = [];
  page.on('request', request => { if (/font-identifier-(?:engine|worker)/.test(request.url())) requests.push(request.url()); });
  page.on('pageerror', error => errors.push(error.message));
  for (const width of [1440, 1024, 390, 320]) {
    await page.setViewportSize({ width, height: width < 1024 ? 844 : 900 });
    await page.goto('/');
    const results = page.locator('#generated-results');
    const first = await results.locator('article').first().boundingBox();
    expect(first!.y).toBeLessThan(width < 1024 ? 700 : 550);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await expect(page.getByRole('region', { name: 'Selected font preview', exact: true })).toHaveCount(0);
    await page.screenshot({ path: '/tmp/home-focus-implemented-' + width + '.png', animations: 'disabled' });
    const directory = page.getByRole('complementary', { name: 'Generator directory', exact: true });
    if (width < 1024) {
      await expect(directory).toBeHidden();
      const button = page.getByRole('button', { name: /^Generators/ });
      await button.click();
      await expect(directory).toBeVisible();
      await expect(directory.getByRole('searchbox')).toBeFocused();
      await expect(directory.getByRole('navigation', { name: 'Copyable text generators', exact: true }).locator('li')).toHaveCount(33);
      await expect(directory.getByRole('navigation', { name: 'Visual and art generators', exact: true }).locator('li')).toHaveCount(18);
      await page.keyboard.press('Escape');
      await expect(directory).toBeHidden();
      await expect(button).toBeFocused();
    } else {
      await expect(directory).toBeVisible();
      const a = await results.locator('article').nth(0).boundingBox(), b = await results.locator('article').nth(1).boundingBox();
      expect(a!.y).toBe(b!.y);
      expect(b!.x).toBeGreaterThan(a!.x);
    }
    await page.locator('#generator-input').fill('字 👨‍👩‍👧‍👦 ' + 'x'.repeat(200));
    await page.getByRole('button', { name: 'Preview Bold Serif Font', exact: true }).click();
    await expect(page.getByRole('region', { name: 'Selected font preview' })).toContainText('👨‍👩‍👧‍👦');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByRole('button', { name: 'Close preview', exact: true }).click();
    await page.getByRole('button', { name: 'Switch to dark mode', exact: true }).click();
    await expect(page.locator('html')).toHaveClass(/dark/);
    await page.screenshot({ path: '/tmp/home-focus-implemented-dark-' + width + '.png', animations: 'disabled' });
    await page.getByRole('button', { name: 'Switch to light mode', exact: true }).click();
  }
  await page.goto('/');
  const artwork = page.getByRole('navigation', { name: 'Visual & Art Generators', exact: true });
  await expect(artwork.locator('a')).toHaveCount(5);
  await artwork.getByRole('button', { name: /Load more generators/ }).click();
  await expect(artwork.locator('a')).toHaveCount(9);
  await artwork.getByRole('button', { name: 'Collapse to 4', exact: true }).click();
  await expect(artwork.locator('a')).toHaveCount(5);
  await artwork.getByRole('link', { name: 'View all', exact: false }).click();
  await expect(page).toHaveURL(/\/visual-art$/);
  expect(requests).toEqual([]);
  expect(errors).toEqual([]);
});
