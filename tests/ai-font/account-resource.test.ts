import { test } from 'node:test';
import assert from 'node:assert/strict';
import { accountResource, fetchAccount } from '../../lib/ai-font/account-resource';
import { authChangedEvent } from '../../lib/ai-font/auth-navigation';

test('account requests deduplicate, stay in memory and discard responses from an old identity', async context => {
  const originalFetch = globalThis.fetch;
  const originalWindow = Object.getOwnPropertyDescriptor(globalThis, 'window');
  const surface = new EventTarget();
  Object.defineProperty(globalThis, 'window', { configurable: true, value: surface });
  context.after(() => { globalThis.fetch = originalFetch; if (originalWindow) Object.defineProperty(globalThis, 'window', originalWindow); else Reflect.deleteProperty(globalThis, 'window'); });
  let calls = 0;
  const fixture = { user: { email: 'first@example.com' }, credits: 300, jobs: [], orders: [], services: { auth: true, generation: true, checkout: true, sandbox: true } };
  globalThis.fetch = async (_input, init) => { calls++; assert.equal(init?.cache, 'no-store'); assert.ok(init?.signal); return Response.json(fixture); };
  await Promise.all([fetchAccount(), fetchAccount()]);
  assert.equal(calls, 1);
  await fetchAccount(); assert.equal(calls, 1);
  await fetchAccount(true); assert.equal(calls, 2);
  surface.dispatchEvent(new Event(authChangedEvent));
  assert.equal(accountResource.getSnapshot().account, null);
  await fetchAccount(); assert.equal(calls, 3);
  let resolveOld!: (response: Response) => void;
  globalThis.fetch = () => new Promise(resolve => { resolveOld = resolve; });
  const old = fetchAccount(true);
  surface.dispatchEvent(new Event(authChangedEvent));
  assert.equal(accountResource.getSnapshot().account, null);
  globalThis.fetch = async () => Response.json({ ...fixture, user: { email: 'second@example.com' } });
  await fetchAccount();
  resolveOld(Response.json(fixture));
  assert.equal((await old).user?.email, 'second@example.com');
  assert.equal((await fetchAccount()).user?.email, 'second@example.com');
  globalThis.fetch = () => new Promise(resolve => { resolveOld = resolve; });
  const beforeMutation = fetchAccount(true);
  globalThis.fetch = async () => Response.json({ ...fixture, user: { email: 'second@example.com' }, credits: 200 });
  await fetchAccount(true);
  resolveOld(Response.json({ ...fixture, user: { email: 'second@example.com' }, credits: 300 }));
  assert.equal((await beforeMutation).credits, 200, 'an older GET cannot replace the refreshed post-mutation balance');
  surface.dispatchEvent(new Event(authChangedEvent));
  const controller = new AbortController();
  context.mock.method(AbortSignal, 'timeout', () => controller.signal);
  globalThis.fetch = (_input, init) => new Promise((_resolve, reject) => init?.signal?.addEventListener('abort', () => reject(init.signal?.reason), { once: true }));
  const slow = fetchAccount();
  controller.abort(new DOMException('timeout', 'TimeoutError'));
  await assert.rejects(slow, /taking longer than expected/);
  assert.equal(accountResource.getSnapshot().loading, false);
  assert.equal(accountResource.getSnapshot().account, null);
});
